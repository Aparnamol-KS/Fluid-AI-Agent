import re
from datetime import datetime, timezone
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = PROJECT_ROOT / "outputs"


def clean_inline(text: str) -> str:
    """Normalize basic HTML and Markdown formatting."""
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    text = re.sub(r"__(.*?)__", r"\1", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    return text.strip()

def is_table_line(line: str) -> bool:
    """Identify a Markdown table row."""
    line = line.strip()
    return "|" in line and line.count("|") >= 2


def is_separator_row(line: str) -> bool:
    """Recognize Markdown table separator rows such as |---|---|."""
    cells = parse_table_row(line)
    return bool(cells) and all(
        re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in cells
    )


def parse_table_row(line: str) -> list[str]:
    """Split a Markdown table row into cells."""
    line = line.strip()

    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]

    return [clean_inline(cell) for cell in line.split("|")]


def add_markdown_table(doc: Document, rows: list[str]) -> None:
    """Convert Markdown table rows into a native Word table."""
    parsed_rows = [parse_table_row(row) for row in rows if not is_separator_row(row)]

    if not parsed_rows:
        return

    column_count = max(len(row) for row in parsed_rows)
    table = doc.add_table(rows=0, cols=column_count)
    table.style = "Table Grid"
    table.autofit = True

    for row_index, values in enumerate(parsed_rows):
        cells = table.add_row().cells

        for col_index in range(column_count):
            value = values[col_index] if col_index < len(values) else ""
            paragraph = cells[col_index].paragraphs[0]
            paragraph.paragraph_format.space_after = Pt(3)

            run = paragraph.add_run(value)
            run.font.size = Pt(9)

            if row_index == 0:
                run.bold = True
                run.font.color.rgb = RGBColor(31, 78, 121)

    doc.add_paragraph()


def create_docx(
    title: str,
    document_type: str,
    content: str,
    assumptions: list[str],
) -> Path:
    """Create a formatted Word document from Markdown-like content."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    safe_title = re.sub(r"[^a-zA-Z0-9_-]+", "_", title).strip("_")
    safe_title = safe_title[:60] or "business_document"
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    output_path = OUTPUT_DIR / f"{safe_title}_{timestamp}.docx"

    doc = Document()
    section = doc.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.75)
    section.right_margin = Inches(0.75)

    styles = doc.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(10)
    styles["Normal"].font.color.rgb = RGBColor(45, 55, 72)

    styles["Heading 1"].font.name = "Aptos Display"
    styles["Heading 1"].font.size = Pt(16)
    styles["Heading 1"].font.color.rgb = RGBColor(31, 78, 121)

    styles["Heading 2"].font.name = "Aptos Display"
    styles["Heading 2"].font.size = Pt(12)
    styles["Heading 2"].font.color.rgb = RGBColor(31, 78, 121)

    heading = doc.add_heading(title, level=0)
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle.add_run(document_type.replace("_", " ").title()).italic = True

    doc.add_paragraph("Generated by the Fluid AI Autonomous Agent assessment project")

    if assumptions:
        doc.add_heading("Assumptions", level=1)
        for assumption in assumptions:
            doc.add_paragraph(
                clean_inline(assumption),
                style="List Bullet",
            )

    lines = content.splitlines()
    i = 0

    while i < len(lines):
        line = lines[i].strip()

        if not line:
            i += 1
            continue

        # Collect a consecutive Markdown table block.
        if is_table_line(line):
            table_rows = []

            while i < len(lines) and is_table_line(lines[i].strip()):
                table_rows.append(lines[i].strip())
                i += 1

            add_markdown_table(doc, table_rows)
            continue

        if line.startswith("### "):
            doc.add_heading(clean_inline(line[4:]), level=2)
        elif line.startswith("## "):
            doc.add_heading(clean_inline(line[3:]), level=1)
        elif line.startswith("# "):
            doc.add_heading(clean_inline(line[2:]), level=1)
        elif line.startswith(("- ", "* ")):
            doc.add_paragraph(
                clean_inline(line[2:]),
                style="List Bullet",
            )
        elif re.match(r"^\d+[.)]\s+", line):
            text = re.sub(r"^\d+[.)]\s+", "", line)
            doc.add_paragraph(
                clean_inline(text),
                style="List Number",
            )
        elif line == "---":
            doc.add_paragraph()
        else:
            doc.add_paragraph(clean_inline(line))

        i += 1

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run("Generated document | Fluid AI Agent")

    doc.save(output_path)
    return output_path
